import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { PublishedResearch } from '../src/publication.ts';

const schema = 'marketlens-research-v1';
const data = { schema, kind: 'real_research_snapshot', overview: { scan: {mode: 'yahoo', candidates: [{mode: 'yahoo'}]}, paper: {private: true} }, settings: {}, stocks: {} };
const body = JSON.stringify(data);
let manifest = { schema, kind: data.kind, data_commit: 'a'.repeat(40), content_hash: createHash('sha256').update(body).digest('hex'), published_at: new Date().toISOString() };
let fail = false, corrupt = false, reads = 0;
const fetcher = async url => {
  assert(url.startsWith('https://raw.githubusercontent.com/owner/repo/'));
  if (fail) throw new Error('Network unavailable');
  if (url.includes('/latest.json')) return new Response(JSON.stringify(manifest));
  assert(url.includes(`/${manifest.data_commit}/data.json`));
  reads += 1;
  return new Response(corrupt ? body + 'corruption' : body);
};
const client = new PublishedResearch('owner/repo', 'research-data', fetcher);
const first = await client.load();
assert.equal(first.overview.scan.mode, 'yahoo');
assert.equal(reads, 1);
manifest = {...manifest, published_at: new Date().toISOString()};
await client.load(true);
assert.equal(reads, 1, 'Unchanged datasets must not be downloaded on every heartbeat');
const newest = manifest.published_at;
manifest = {...manifest, published_at: '2020-01-01T00:00:00Z'};
assert.equal((await client.load(true)).overview.publication.published_at, newest);
assert.match(client.data.overview.publication.error, /older cached/);
manifest = {...manifest, published_at: newest};
fail = true;
const retained = await client.load(true);
assert.equal(retained.overview.scan.mode, 'yahoo');
assert.match(retained.overview.publication.error, /Network unavailable/);
fail = false;
corrupt = true;
await assert.rejects(new PublishedResearch('owner/repo', 'research-data', fetcher).load(), /checksum mismatch/);
corrupt = false;
manifest = {...manifest, data_commit: '../../other-host'};
await assert.rejects(new PublishedResearch('owner/repo', 'research-data', fetcher).load(), /Invalid published/);
const fixture = JSON.stringify({...data, kind: 'synthetic_static_fixture'});
const invalid = new PublishedResearch('owner/repo', 'research-data', async url => new Response(url.includes('/latest.json') ? JSON.stringify({...manifest, data_commit: 'b'.repeat(40), content_hash: createHash('sha256').update(fixture).digest('hex')}) : fixture));
await assert.rejects(invalid.load(), /not a valid actual/);
assert.throws(() => new PublishedResearch('https://other.example/private'), /Invalid public/);
console.log('Published reader checks passed: immutable commit, checksum, heartbeat reuse, failed-check retention, source separation and URL confinement.');
